import json

from model_contract import split_top

SAFE = 9007199254740991


def add_artifacts(artifacts, models, enums, request, commands, unused_ts, enum_declarations):
    def structural(t):
        if t in models:
            return {"$ref": "#/$defs/" + t}
        if t in enums:
            return {"type": "string", "enum": enums[t]}
        if t == "RemoteCommand":
            return {"$ref": "#/$defs/RemoteCommand"}
        if t == "UUID":
            return {"type": "string", "format": "uuid"}
        if t == "String":
            return {"type": "string", "maxLength": 65536}
        if t == "Data":
            return {"type": "string", "contentEncoding": "base64"}
        if t == "Bool":
            return {"type": "boolean"}
        if t in ("Int", "UInt32", "UInt64"):
            return {
                "type": "integer",
                "minimum": 0 if t in ("UInt32", "UInt64") else -SAFE,
                "maximum": 4294967295 if t == "UInt32" else SAFE,
            }
        if t == "UInt64String":
            return {
                "type": "string",
                "pattern": "^(0|[1-9][0-9]{0,19})$",
                "description": "Exact decimal UInt64; max18446744073709551615",
            }
        if t in ("Float", "Double", "Date"):
            return {"type": "number", "minimum": -SAFE, "maximum": SAFE}
        if t == "Range<Int>":
            return {
                "type": "array",
                "prefixItems": [structural("Int"), structural("Int")],
                "minItems": 2,
                "maxItems": 2,
            }
        if t.startswith("["):
            interior = t[1:-1]
            pair = split_top(interior, ":")
            if len(pair) == 1:
                return {"type": "array", "items": structural(interior), "maxItems": 100000}
            result = {
                "type": "object",
                "additionalProperties": structural(pair[1]),
                "maxProperties": 1024,
            }
            if pair[0] == "UUID":
                result["propertyNames"] = {"format": "uuid"}
            return result
        raise ValueError("Unsupported contract type " + t)

    defs = {}
    for name, record in models.items():
        props = {}
        for field in record["fields"]:
            definition = structural(field["type"])
            if field["optional"]:
                definition = {"anyOf": [definition, {"type": "null"}]}
            props[field["name"]] = definition
        defs[name] = {
            "type": "object",
            "additionalProperties": False,
            "properties": props,
            "required": [f["name"] for f in record["fields"] if f["required"]],
        }
    defs["RemoteCommand"] = request["properties"]["command"]
    defs["Session"]["properties"]["version"] = {"type": "integer", "minimum": 1, "maximum": 10}
    defs["MusicalTiming"]["properties"].update(
        tempo={"type": "number", "minimum": 20, "maximum": 300},
        beatsPerBar={"type": "integer", "minimum": 1, "maximum": 16},
        beatUnit={"enum": [2, 4, 8, 16]},
    )
    for name in ("Track", "RemoteTrackControls"):
        defs[name]["properties"]["gain"] = {"type": "number", "minimum": 0, "maximum": 4}
        defs[name]["properties"]["pan"] = {"type": "number", "minimum": -1, "maximum": 1}
    patch = defs["RemoteTrackControlPatch"]
    patch["properties"]["gain"] = {
        "anyOf": [{"type": "number", "minimum": 0, "maximum": 4}, {"type": "null"}]
    }
    patch["properties"]["pan"] = {
        "anyOf": [{"type": "number", "minimum": -1, "maximum": 1}, {"type": "null"}]
    }
    patch["anyOf"] = [
        {"required": [name], "properties": {name: {"not": {"type": "null"}}}}
        for name in ("gain", "pan", "muted", "solo", "armed")
    ]
    patches = defs["RemoteSessionDelta"]["properties"]["controlPatches"]["anyOf"][0]
    patches.update(
        maxItems=1024,
        description="One patch per case-insensitive UUID; duplicate target identities rejected by runtime validators.",
    )
    from write_contract import add_artifacts as add_write_artifacts

    add_write_artifacts(artifacts, defs)
    request["$defs"] = defs
    artifacts["protocol/generated/request.schema.json"] = json.dumps(request, indent=2) + "\n"
    messages = json.loads(artifacts["protocol/generated/messages.schema.json"])
    messages["$defs"] = defs
    messages["oneOf"][0]["properties"]["capabilities"] = {"$ref": "#/$defs/RemoteCapabilities"}
    artifacts["protocol/generated/messages.schema.json"] = json.dumps(messages, indent=2) + "\n"
    artifacts["protocol/generated/session.schema.json"] = (
        json.dumps(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$id": "https://soundroom.local/protocol/v3/session.schema.json",
                "$ref": "#/$defs/Session",
                "$defs": defs,
            },
            indent=2,
        )
        + "\n"
    )
    swift = [
        "// Generated by protocol/generate.py; do not edit.",
        "import Foundation",
        "enum RemoteV3Models {",
        "    static let records: [String: [(name: String, type: String, optional: Bool, required: Bool)]] = [",
    ]
    for name, record in sorted(models.items()):
        swift.append(
            "        "
            + json.dumps(name)
            + ": ["
            + ", ".join(
                "("
                + ", ".join(
                    [
                        json.dumps(f["name"]),
                        json.dumps(f["type"]),
                        "true" if f["optional"] else "false",
                        "true" if f["required"] else "false",
                    ]
                )
                + ")"
                for f in record["fields"]
            )
            + "],"
        )
    swift += ["    ]", "    static let enums: [String: Set<String>] = ["]
    for name, values in sorted(enums.items()):
        swift.append(
            "        " + json.dumps(name) + ": [" + ", ".join(json.dumps(v) for v in values) + "],"
        )
    swift += ["    ]", "}"]
    artifacts["Sources/SoundroomRemote/RemoteV3Models.swift"] = "\n".join(swift) + "\n"
    ts = [
        "// Generated by protocol/generate.py; do not edit.",
        "import type {RemoteCommand} from './contract';",
    ]

    def typed(t):
        if t in models or t in enums or t == "RemoteCommand":
            return t
        if t in ("String", "UUID", "UInt64String", "Data"):
            return "string"
        if t in ("Int", "UInt32", "UInt64", "Float", "Double", "Date"):
            return "number"
        if t == "Bool":
            return "boolean"
        if t == "Range<Int>":
            return "[number,number]"
        if t.startswith("["):
            pair = split_top(t[1:-1], ":")
            return (
                "(" + typed(pair[0]) + ")[]"
                if len(pair) == 1
                else "Record<string," + typed(pair[1]) + ">"
            )
        raise ValueError("Unsupported TS model " + t)

    for name, values in sorted(enums.items()):
        ts.append("export type " + name + " = " + "|".join(json.dumps(v) for v in values) + ";")
    for name, record in sorted(models.items()):
        ts.append(
            "export interface "
            + name
            + " {"
            + "".join(
                f["name"]
                + ("?" if not f["required"] else "")
                + ":"
                + typed(f["type"])
                + ("|null" if f["optional"] else "")
                + ";"
                for f in record["fields"]
            )
            + "}"
        )
    ts.append(
        "export const modelFields = "
        + json.dumps({n: r["fields"] for n, r in models.items()}, indent=2)
        + " as const;"
    )
    ts.append("export const modelEnums = " + json.dumps(enums, indent=2) + " as const;")
    artifacts["protocol/generated/models.ts"] = "\n".join(ts) + "\n"

    tests = [
        "// Generated by protocol/generate.py; do not edit.",
        "import XCTest",
        "import SoundroomCore",
        "@testable import SoundroomRemote",
        "",
        "final class RemoteV3EnumParityTests: XCTestCase {",
        "    func testEveryNativeCodableEnumMatchesItsGeneratedWireValues() throws {",
    ]
    for name, declaration in sorted(enum_declarations.items()):
        qualified = declaration["nativeName"]
        native = (
            qualified + ".allCases"
            if declaration["iterable"]
            else "["
            + ", ".join(qualified + "." + entry["identifier"] for entry in declaration["entries"])
            + "]"
        )
        tests.append("        try assertEnum(" + native + ", type: " + json.dumps(name) + ")")
    tests += [
        "    }",
        "    private func assertEnum<T: Encodable>(_ cases: [T], type: String) throws {",
        "        let values = try cases.map { value -> String in",
        "            let data = try JSONEncoder().encode(value)",
        "            try RemoteV3ModelValidator.validateJSON(data, type: type)",
        "            return try XCTUnwrap(JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]) as? String)",
        "        }",
        "        XCTAssertEqual(Set(values), RemoteV3Models.enums[type], type)",
        "        XCTAssertEqual(values.count, RemoteV3Models.enums[type]?.count, type)",
        "    }",
        "}",
    ]
    artifacts["Tests/SoundroomRemoteTests/RemoteV3EnumParityTests.swift"] = "\n".join(tests) + "\n"
