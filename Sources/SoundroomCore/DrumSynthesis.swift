import Foundation

/// Original procedural drum voices; these are modeled instruments, not recordings.
public enum DrumKit: String, Codable, CaseIterable, Identifiable, Sendable {
    case acoustic, electronic, jazzMaple, rockBirch, vintageDry, brushed, orchestral
    case funkTight, vintageWarm, arenaRock, machine808, machine909, lofiDusty, trapModern, technoMinimal
    /// Recorded multi-mic kit (DRSKit, CC BY 4.0) mixed by the Rust host;
    /// this engine renders them with the modeled acoustic studio voice.
    case studioNatural, studioTight, studioRoom, studioVintage
    /// Generated by the Rust host from measurements of the recorded kit.
    case studioModeled
    public var id: Self { self }
    public var isAcoustic: Bool { machineVoicing == nil }
    /// Recorded or measured kits rendered by the Rust host; this engine
    /// substitutes the modeled acoustic studio voice.
    public var isRecorded: Bool {
        [.studioNatural, .studioTight, .studioRoom, .studioVintage, .studioModeled].contains(self)
    }
    public var title: String {
        switch self {
        case .acoustic: return "Acoustic studio"
        case .electronic: return "Electronic analog"
        case .jazzMaple: return "Maple jazz · open"
        case .rockBirch: return "Birch rock · punch"
        case .vintageDry: return "Vintage · damped"
        case .brushed: return "Brushes · intimate"
        case .orchestral: return "Orchestral · resonant"
        case .funkTight: return "Studio funk · tight"
        case .vintageWarm: return "Vintage · warm 60s"
        case .arenaRock: return "Arena rock · big room"
        case .machine808: return "808 · boom"
        case .machine909: return "909 · punch"
        case .lofiDusty: return "Lo-fi · dusty sampler"
        case .trapModern: return "Trap · modern 808"
        case .technoMinimal: return "Techno · driven"
        case .studioNatural: return "Recorded kit · natural"
        case .studioTight: return "Recorded kit · tight close mics"
        case .studioRoom: return "Recorded kit · big room"
        case .studioVintage: return "Recorded kit · vintage overheads"
        case .studioModeled: return "Modeled from recordings"
        }
    }
    var profile: (pitch: Double, body: Double, wires: Double, metal: Double, brush: Bool) {
        switch self {
        case .jazzMaple: return (1.18, 1.3, 0.9, 0.85, false)
        case .rockBirch: return (0.87, 0.95, 1.2, 1.08, false)
        case .vintageDry: return (0.94, 0.45, 0.75, 0.75, false)
        case .brushed: return (1.08, 0.7, 1.0, 0.65, true)
        case .orchestral: return (0.72, 1.55, 0.8, 0.78, false)
        case .funkTight: return (1.12, 0.62, 1.15, 1.02, false)
        case .vintageWarm: return (0.96, 0.8, 0.9, 0.82, false)
        case .arenaRock: return (0.8, 1.45, 1.12, 1.05, false)
        default: return (1, 1, 1, 1, false)
        }
    }
    /// Drum-machine voicing; nil for modeled acoustic kits.
    var machineVoicing: DrumMachineVoicing? {
        let classic = DrumMachineVoicing()
        var v = classic
        switch self {
        case .electronic: return classic
        case .machine808:
