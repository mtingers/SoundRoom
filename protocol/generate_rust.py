"""Generate typed portable models and descriptors; wire validation stays explicit."""

import json
import re

from model_contract import split_top


def add_rust_artifacts(artifacts, models, enums, commands, events, declarations):
    def typ(t):
        if t in models or t in enums or t == "RemoteCommand":
            return t
        if t in ("String", "UUID", "UInt64String", "Data"):
            return "String"
        if t in ("Int",):
            return "i64"
        if t == "UInt32":
            return "u32"
        if t == "UInt64":
            return "u64"
        if t in ("Float",):
            return "f32"
        if t in ("Double", "Date"):
            return "f64"
        if t == "Bool":
            return "bool"
        if t == "Range<Int>":
            return "[i64; 2]"
        if t.startswith("["):
            parts = split_top(t[1:-1], ":")
            return (
                "Vec<" + typ(parts[0]) + ">"
                if len(parts) == 1
                else "BTreeMap<String, " + typ(parts[1]) + ">"
            )
        raise ValueError("Unsupported Rust model " + t)

    def ident(s):
        s = s.replace("IDs", "Ids")
        s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
        s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
        return (
            "r#" + s
            if s
            in [
                "type",
                "match",
                "loop",
                "ref",
                "self",
                "enum",
                "struct",
                "move",
                "pub",
                "use",
                "fn",
                "mod",
                "trait",
                "impl",
                "async",
                "await",
                "in",
                "where",
                "const",
                "static",
                "return",
                "break",
                "continue",
                "crate",
                "super",
            ]
            else s
        )

    lines = [
        "// Generated by protocol/generate.py; do not edit.",
        "use serde::{Deserialize, Serialize};",
        "use std::collections::BTreeMap;",
        "",
    ]
    for name, values in sorted(enums.items()):
        lines += [
            "#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]",
            "pub enum " + name + " {",
        ]
        for entry in declarations[name]["entries"]:
            variant = entry["identifier"].strip("`")
            variant = variant[0].upper() + variant[1:]
            lines += [
                "    #[serde(rename = " + json.dumps(entry["value"]) + ")]",
                "    " + variant + ",",
            ]
        lines += ["}", ""]
    for name, record in sorted(models.items()):
        derives = (
            "Clone, PartialEq, Serialize, Deserialize"
            if name in ("RemoteCredential", "RemoteBrowserCredential", "RemoteWebPairingGrant")
            else "Clone, Debug, PartialEq, Serialize, Deserialize"
        )
        lines += [
            "#[derive(" + derives + ")]",
            "#[serde(deny_unknown_fields)]",
            "pub struct " + name + " {",
        ]
        for field in record["fields"]:
            field_type = typ(field["type"])
            attributes = ["rename = " + json.dumps(field["name"])]
            if not field["required"]:
                field_type = "Option<" + field_type + ">"
                attributes += ["default", 'skip_serializing_if = "Option::is_none"']
            lines += [
                "    #[serde(" + ", ".join(attributes) + ")]",
                "    pub " + ident(field["name"]) + ": " + field_type + ",",
            ]
        lines += ["}", ""]
    for name, items in [("RemoteCommand", commands), ("RemoteEvent", events)]:
        lines += [
            "#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]",
            '#[serde(tag = "type", deny_unknown_fields)]',
            "pub enum " + name + " {",
        ]
        for tag, fields in items.items():
            variant = tag[0].upper() + tag[1:]
            lines += [
                "    #[serde(rename = " + json.dumps(tag) + ")]",
                "    " + variant + (" {" if fields else ","),
            ]
            for field in fields:
                t = typ(field["type"])
                attrs = ["rename = " + json.dumps(field["name"])]
                if name == "RemoteEvent" and field["type"] in (
                    "RemoteSnapshot",
                    "RemoteSessionDelta",
                ):
                    t = "Box<" + t + ">"
                if field["optional"]:
                    t = "Option<" + t + ">"
                    attrs += ["default", 'skip_serializing_if = "Option::is_none"']
                lines += [
                    "        #[serde(" + ", ".join(attrs) + ")]",
                    "        " + ident(field["name"]) + ": " + t + ",",
                ]
            if fields:
                lines += ["    },"]
        lines += ["}", ""]
    lines += [
        "#[derive(Clone, Copy, Debug)]",
        "pub struct ModelField { pub name: &'static str, pub kind: &'static str, pub optional: bool, pub required: bool }",
        "pub const MODEL_FIELDS: &[(&str, &[ModelField])] = &[",
    ]
    for name, record in sorted(models.items()):
        lines += ["    (" + json.dumps(name) + ", &["]
        for f in record["fields"]:
            lines += [
                "        ModelField { name: "
                + json.dumps(f["name"])
                + ", kind: "
                + json.dumps(f["type"])
                + ", optional: "
                + str(f["optional"]).lower()
                + ", required: "
                + str(f["required"]).lower()
                + " },"
            ]
        lines += ["    ]),"]
    lines += ["];", "pub const MODEL_ENUMS: &[(&str, &[&str])] = &["]
    for name, values in sorted(enums.items()):
        lines += [
            "    (" + json.dumps(name) + ", &[" + ", ".join(json.dumps(v) for v in values) + "]),"
        ]
    lines += ["];"]
    for descriptor, entries in [("COMMAND_FIELDS", commands), ("EVENT_FIELDS", events)]:
        lines += ["pub const " + descriptor + ": &[(&str, &[ModelField])] = &["]
        for name, fields in entries.items():
            lines += ["    (" + json.dumps(name) + ", &["]
            for f in fields:
                lines += [
                    "        ModelField { name: "
                    + json.dumps(f["name"])
                    + ", kind: "
                    + json.dumps(f["type"])
                    + ", optional: "
                    + str(f["optional"]).lower()
                    + ", required: "
                    + str(not f["optional"]).lower()
                    + " },"
                ]
            lines += ["    ]),"]
        lines += ["];"]
    artifacts["protocol/generated/models.rs"] = "\n".join(lines) + "\n"
