            v.snareToneDecay = 0.045
            v.snareNoiseGain = 0.62
            v.snareNoiseDecay = 0.11
            v.clapGain = 0.45
            v.clapTailGain = 0.2
            v.clapTail = 0.1
            v.metalScale = 1.6
            v.hatNoise = 0.5
            v.hatMetal = 0.1
        case .lofiDusty:
            // Sampler grit: reduced resolution, held samples and a dark top end.
            v.kickBase = 50
            v.kickSweep = 2.2
            v.kickDecay = 0.2
            v.kickClick = 0.12
            v.kickDrive = 1.3
            v.snareNoiseGain = 0.5
            v.snareNoiseDecay = 0.09
